export const MISSION_START_DATE = new Date('2024-01-01T00:00:00Z')

export function getCurrentSol() {
  const earthDays = (Date.now() - MISSION_START_DATE.getTime()) / (1000 * 60 * 60 * 24)
  return Math.floor(earthDays / 1.027491) + 1
}

